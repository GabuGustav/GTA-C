// ---------------------------------------------------------------------------
// getVehicleTable()  — client-side UI list builder
// ---------------------------------------------------------------------------
function getVehicleTable() {
    const t = vehicleTables[getGame()];
    if (!t) return [];
    return Object.entries(t)
        .map(([name, model]) => ({ name, model }))
        .sort((a, b) => a.name.localeCompare(b.name));
}